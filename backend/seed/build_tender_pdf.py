def _wrap(text: str, width: int = CHARS_PER_LINE):
    lines, cur = [], ""
    for ch in text:
        cur += ch
        if len(cur) >= width and (ch in "。；;！!？?、 ）)】」" or len(cur) >= width + 8):
            lines.append(cur)
            cur = ""
    if cur:
        lines.append(cur)
    return lines


def _add_page(doc):
    page = doc.new_page(width=PAGE_W, height=PAGE_H)
    # 页眉
    page.insert_text((ML, 42), "智能制造装备采购项目招标文件（招标编号：ZB-2026-AH-0107）",
                     fontname=FONT_CN, fontsize=8.5, color=(0.45, 0.45, 0.45))
    return page


def _new_page_if_needed(doc, page, y, need_lines):
    if y + need_lines * LINE_H_BODY > PAGE_H - MB:
        return _add_page(doc), MT
    return page, y


